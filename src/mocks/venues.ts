import type { Business, MediaAsset, Offer, Venue } from "@/types";

/**
 * Fixture data for the pilot vertical.
 *
 * Media is expressed as deterministic gradient artwork rather than image URLs.
 * Two reasons, both commercial: the demo must render perfectly in a club
 * basement with no wifi, and we are not shipping scraped photography of real
 * venues we have no licence for. `MediaAsset.url` already exists on the type,
 * so production swaps bytes in without a component change.
 */

const media = (
  id: string,
  alt: string,
  gradient: [string, string],
  accent: string,
  kind: MediaAsset["kind"] = "image",
): MediaAsset => ({
  id,
  kind,
  gradient,
  accent,
  alt,
  width: 1200,
  height: 800,
});

const standardHours = (
  openAt: string,
  closeAt: string,
  closedDays: number[] = [],
) =>
  [0, 1, 2, 3, 4, 5, 6].map((day) => ({
    day,
    opensAt: openAt,
    closesAt: closeAt,
    closed: closedDays.includes(day),
  }));

